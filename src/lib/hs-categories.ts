export function hsChapterName(code: string): string | null {
  const digits = code.replace(/\D/g, "").padEnd(2, " ").slice(0, 2);
  return HS_CHAPTERS[digits] ?? null;
}

/** HS 코드 배열에서 중복 제거된 카테고리(2자리 챕터) 라벨을 추출 */
export function hsCategoriesFromCodes(codes: string[]): string[] {
  const set = new Set<string>();
  for (const c of codes) {
    const name = hsChapterName(c);
    if (name) set.add(name);
  }
  return Array.from(set);
}
